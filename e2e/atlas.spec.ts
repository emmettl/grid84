import { test, expect } from './fixtures'

test('provenance starts collapsed and opens the selected source with the keyboard', async ({ page }) => {
  await page.goto('/#/lab/evidence')
  const provenance = page.locator('.provenance-disclosure')
  await expect(provenance).not.toHaveAttribute('open', '')
  await page.getByRole('slider', { name: 'Scrub study time' }).press('End')
  await page.getByRole('button', { name: 'A MODELLED EVENT NAMES ITS MODEL (MODELLED)' }).click()
  await expect(provenance.locator('summary')).toContainText('MODELLED RINGS')
  await expect(provenance.getByRole('heading', { name: 'MODELLED RINGS MODELLED' })).toBeHidden()
  await provenance.locator('summary').focus()
  await page.keyboard.press('Enter')
  await expect(provenance.getByRole('heading', { name: 'MODELLED RINGS MODELLED' })).toBeVisible()
  await page.keyboard.press('Space')
  await expect(provenance).not.toHaveAttribute('open', '')
})

test('phone readout scrolls as one sheet and can be folded away', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 568 })
  await page.goto('/#/lab/evidence')
  const sheet = page.locator('.study-sheet')
  const outcome = page.getByRole('region', { name: 'Aggregate outcome' })
  await expect(outcome).toBeVisible()
  await expect.poll(() => sheet.evaluate((el) => el.scrollHeight > el.clientHeight)).toBe(true)
  await outcome.hover()
  await page.mouse.wheel(0, 400)
  await expect.poll(() => sheet.evaluate((el) => el.scrollTop)).toBeGreaterThan(0)
  expect(await outcome.evaluate((el) => el.scrollTop)).toBe(0)
  await sheet.hover()
  await page.mouse.wheel(0, -1000)
  await page.getByRole('button', { name: 'Hide the readout' }).click()
  await expect(outcome).toBeHidden()
  await page.getByRole('button', { name: 'Show the readout' }).click()
  await expect(outcome).toBeVisible()
})

test('tablet casualty panel stays within the viewport and scrolls its content', async ({ page }) => {
  await page.setViewportSize({ width: 800, height: 480 })
  await page.goto('/#/lab/evidence')
  const outcome = page.getByRole('region', { name: 'Aggregate outcome' })
  await expect(outcome).toBeVisible()
  const bounds = await outcome.boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(800)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(480)
  await expect.poll(() => outcome.evaluate((el) => el.scrollHeight > el.clientHeight)).toBe(true)
  await outcome.hover()
  await page.mouse.wheel(0, 300)
  await expect.poll(() => outcome.evaluate((el) => el.scrollTop)).toBeGreaterThan(0)
})

test('target acquisition supports hold, resume, launch and return to the atlas', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/#/atlas')
  await page.getByRole('combobox', { name: 'ENTER TARGET' }).fill('Test City')
  await page.getByRole('button', { name: 'Acquire', exact: true }).click()
  const console = page.getByRole('region', { name: 'Strike console' })
  await expect(console).toBeVisible()
  await expect(console.getByRole('button', { name: 'Vector now' })).toBeEnabled({ timeout: 45_000 })
  await console.getByRole('button', { name: 'Hold', exact: true }).click()
  await expect(console.getByRole('button', { name: 'Vector now' })).toBeDisabled()
  await console.getByRole('button', { name: 'Resume', exact: true }).click()
  await expect(console.getByRole('button', { name: 'Vector now' })).toBeEnabled()
  await console.getByRole('button', { name: 'Vector now' }).click()
  await expect(console).toBeHidden()
  await expect(page.getByRole('region', { name: 'Study clock' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Aggregate outcome' })).toBeVisible()
  await expect(page.locator('.provenance-disclosure')).not.toHaveAttribute('open', '')
  await page.getByRole('button', { name: /return|atlas/i }).click()
  await expect(page.getByRole('heading', { name: 'Orbital standby' })).toBeVisible()
  expect(errors).toEqual([])
})
