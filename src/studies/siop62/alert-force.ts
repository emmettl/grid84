/**
 * SIOP//62 enactment by execution option. Option 1 is the alert force: the
 * 1,004 delivery systems and about 1,685 weapons that could launch on fifteen
 * minutes' warning. Options 2 to 14 add the force generated by up to fourteen
 * hours of preparation, to the fully generated 3,267 weapons of Table 3. All
 * of it flies from the documented order of battle of mid-1961 to the 1956
 * study's highest-priority complexes. The launchers and the totals are
 * documented; the strengths on each base are reconstructed by stated rules;
 * every assignment of a weapon to a target is inferred.
 */
const SAGAN: Provenance = { source: 'Sagan 1987', locator: 'briefing pp. 48–49; Table 1, 15 July 1961', url: 'https://archive.org/details/SIOP62TheNuclearWarPlanBriefingToPresidentKennedy' }
const EBB798: Provenance = { source: 'National Security Archive EBB 798', locator: '1961 estimate: 80 million Soviet dead from the alert force', url: 'https://nsarchive.gwu.edu/briefing-book/nuclear-vault/2022-07-14/long-classified-us-estimates-nuclear-war-casualties-during' }

