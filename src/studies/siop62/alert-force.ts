/**
 * Air-refuelling areas, from the Chrome Dome record: KC-135s "operating out
 * of bases in the northeast United States, Alaska, and Spain", the BLACK
 * GOAT track over Newfoundland, and a Pacific refuelling on the western
 * route (Wikipedia, Operation Chrome Dome). A bomber leaving North America
 * for the bloc routes through the area that adds least to its great circle
 * and holds there ten minutes. Reconstructed: the areas are documented, the
 * choice per sortie is not.
 */
const REFUEL_AREAS: Array<{ id: string; name: string; position: LngLat }> = [
  { id: 'newfoundland', name: 'BLACK GOAT · Newfoundland', position: [-56.0, 49.5] },
  { id: 'alaska', name: 'Alaska', position: [-150.0, 66.0] },
  { id: 'spain', name: 'Spain', position: [-4.0, 39.5] },
  { id: 'pacific', name: 'Pacific', position: [-142.0, 57.0] },
]
const REFUEL_HOLD_SECONDS = 10 * 60

/** Bombers based in North America refuel en route; those already forward do not. */
function refuelVia(from: LngLat, to: LngLat): { area: (typeof REFUEL_AREAS)[number]; extraMetres: number } | null {
  if (from[0] > -30 && from[0] < 100) return null
  const direct = haversineMetres(from, to)
  let best: { area: (typeof REFUEL_AREAS)[number]; extraMetres: number } | null = null
  for (const area of REFUEL_AREAS) {
    const extra = haversineMetres(from, area.position) + haversineMetres(area.position, to) - direct
    if (!best || extra < best.extraMetres) best = { area, extraMetres: extra }
  }
  return best
}

/** Generation state of the force for an option: 0 is the alert force, 1 the fully generated force. */
export interface ForceGeneration {
  option: number
  hours: number
  /** Fraction of the way from the alert tables to the generated tables; straight line, as the readiness lab draws it. */
  fraction: number
}

export function forceGeneration(option: number): ForceGeneration {
  const hours = optionHours(option)
  return { option, hours, fraction: hours / 14 }
}

/** How each launcher's weapons grow from alert to generated, for the provenance panel. */
export interface LauncherGeneration {
  alert: number
  generated: number
  rule: string
}

function buildLaunchers(generation: ForceGeneration): { launchers: Launcher[]; alertFraction: number; bomberWeaponsNominal: number; growth: Record<string, LauncherGeneration> } {
  const raw = (orderOfBattle as { launchers: RawLauncher[] }).launchers
  const bombers = raw.filter((l) => l.kind === 'b52' || l.kind === 'b52h' || l.kind === 'b47' || l.kind === 'b47r')
  const nominal = bombers.reduce((s, l) => s + (l.aircraft ?? 0) * (l.kind.startsWith('b52') ? 2 : 1), 0)
  const sacNominal = bombers.filter((l) => l.kind !== 'b47r').reduce((s, l) => s + (l.aircraft ?? 0) * (l.kind.startsWith('b52') ? 2 : 1), 0)
  const alertFraction = SAC_AIRCRAFT_WEAPONS_ON_ALERT / sacNominal
  // Theatre aircraft take what remains of Table 3's aircraft weapons once every SAC bomber is generated.
  const tacticalAlert = raw.filter((l) => l.kind === 'tactical').reduce((s, l) => s + (l.weapons ?? 0), 0)
  const tacticalGenerated = GENERATION.aircraftGenerated - nominal
  const f = generation.fraction
  const at = (alert: number, generated: number) => alert + f * (generated - alert)
  const launchers: Launcher[] = []
  const growth: Record<string, LauncherGeneration> = {}
  const exact: Record<string, number> = {}
  const push = (launcher: Launcher, alert: number, generated: number, rule: string) => {
    launchers.push(launcher)
    exact[launcher.id] = launcher.weapons
    growth[launcher.id] = { alert, generated, rule }
  }
  for (const l of raw) {
    const position: LngLat = [l.lon, l.lat]
    if (l.kind === 'b52' || l.kind === 'b52h' || l.kind === 'b47' || l.kind === 'b47r') {
      const wpv = l.kind.startsWith('b52') ? 2 : 1
      const generated = (l.aircraft ?? 0) * wpv
      const alert = generated * alertFraction
      push(
        { id: l.id, name: l.name, kind: 'bomber', position, weapons: at(alert, generated), weaponsPerVehicle: wpv, rangeMetres: l.kind === 'b47r' ? 4_500_000 : Infinity, yieldKt: 1_100, reactionSeconds: REACTION_FIXED, speedMs: wpv === 2 ? B52_MS : B47_MS },
        alert,
        generated,
        `Base strength × ${wpv} weapons × alert fraction ${alertFraction.toFixed(2)} on alert, the fraction chosen so SAC bases carry the documented 1,212 aircraft weapons; every aircraft generated by fourteen hours`,
      )
    } else if (l.kind === 'icbm') {
      const alert = l.weapons ?? 0
      const generated = (alert * GENERATION.icbmTotal) / GENERATION.icbmAlert
      push({ id: l.id, name: l.name, kind: 'icbm', position, weapons: at(alert, generated), weaponsPerVehicle: 1, rangeMetres: 14_000_000, yieldKt: l.yieldKt ?? 1_440, reactionSeconds: REACTION_FIXED }, alert, generated, `Table 1 on alert; ${GENERATION.icbmAlert} of ${GENERATION.icbmTotal} ICBMs were on alert (Sagan p. 29), so the site generates to ${(GENERATION.icbmTotal / GENERATION.icbmAlert).toFixed(2)} times its alert strength`)
    } else if (l.kind === 'irbm') {
      const alert = l.weapons ?? 0
      push({ id: l.id, name: l.name, kind: 'irbm', position, weapons: alert, weaponsPerVehicle: 1, rangeMetres: 2_400_000, yieldKt: l.yieldKt ?? 1_440, reactionSeconds: REACTION_FIXED }, alert, alert, 'Table 1; the Jupiters stood on alert, so generation adds none')
    } else if (l.kind === 'slbm') {
      const alert = l.weapons ?? 0
      const generated = (alert * GENERATION.polarisBoats) / GENERATION.polarisAlertBoats
      push({ id: l.id, name: l.name, kind: 'slbm', position, weapons: at(alert, generated), weaponsPerVehicle: 1, rangeMetres: 2_200_000, yieldKt: l.yieldKt ?? 600, reactionSeconds: REACTION_SEA }, alert, generated, `Two of five Polaris boats on station (Sagan p. 29); all five with strategic warning`)
    } else if (l.kind === 'tactical') {
      const alert = l.weapons ?? 0
      const generated = (alert * tacticalGenerated) / tacticalAlert
      push({ id: l.id, name: l.name, kind: 'bomber', position, weapons: at(alert, generated), weaponsPerVehicle: 1, rangeMetres: 1_800_000, yieldKt: l.yieldKt ?? 70, reactionSeconds: REACTION_FIXED, speedMs: TACTICAL_MS }, alert, generated, `Theatre share of Table 1 on alert; the ${tacticalGenerated} aircraft weapons Table 3 leaves once every SAC bomber is generated, in proportion`)
    } else if (l.kind === 'cruise') {
      const alert = l.weapons ?? 0
      const generated = (alert * GENERATION.cruise.generated) / GENERATION.cruise.alert
      push({ id: l.id, name: l.name, kind: 'bomber', position, weapons: at(alert, generated), weaponsPerVehicle: 1, rangeMetres: 2_000_000, yieldKt: l.yieldKt ?? 1_100, reactionSeconds: REACTION_FIXED, speedMs: MACE_MS }, alert, generated, `Table 1 on alert; Table 3's ${GENERATION.cruise.generated} cruise missiles against ${GENERATION.cruise.alert} on alert, in proportion`)
    }
  }
  // Round per raw kind so that each group's total is the rounded group total, not the sum of roundings.
  for (const kind of new Set(raw.map((l) => l.kind))) {
    const group = launchers.filter((l) => raw.find((r) => r.id === l.id)?.kind === kind)
    const rounded = roundPreservingSum(group.map((l) => exact[l.id]))
    group.forEach((l, i) => (l.weapons = rounded[i]))
  }
  return { launchers, alertFraction, bomberWeaponsNominal: nominal, growth }
}

/** Largest-remainder rounding: integers whose sum is the rounded sum of the inputs. */
export function roundPreservingSum(values: number[]): number[] {
  const floors = values.map((v) => Math.floor(v))
  let short = Math.round(values.reduce((a, b) => a + b, 0)) - floors.reduce((a, b) => a + b, 0)
  const order = values.map((v, i) => ({ i, r: v - floors[i] })).sort((a, b) => b.r - a.r)
  for (const { i } of order) {
    if (short <= 0) break
    floors[i] += 1
    short -= 1
  }
  return floors
}

/** Priority offset that places every complex after every airfield: the study's first task is the Air Power Battle. */
const COMPLEX_AFTER_AIRFIELDS = 10_000

export interface TargetMeta {
  kind: 'airfield' | 'complex'
  categories?: string[]
}
export const TARGET_META: Record<string, TargetMeta> = {}

function buildTargets(): Target[] {
  const airfields = (airfieldFile as { targets: Array<{ be: string; priority: number; name: string; lat: number; lon: number }> }).targets.map((a) => {
    TARGET_META[`a-${a.be}`] = { kind: 'airfield' }
    return { id: `a-${a.be}`, name: a.name, priority: a.priority, position: [a.lon, a.lat] as LngLat }
  })
  const complexes = (targetFile as { targets: Array<{ complex: string; priority: number; name: string; lat: number; lon: number; categoryNames?: string[] }> }).targets.map((t) => {
    TARGET_META[`t-${t.complex}`] = { kind: 'complex', categories: t.categoryNames }
    return { id: `t-${t.complex}`, name: t.name, priority: t.priority + COMPLEX_AFTER_AIRFIELDS, position: [t.lon, t.lat] as LngLat }
  })
  return [...airfields, ...complexes]
}

